"""У проверки заявленных чисел есть своё число чувствительности (#577).

Проверка чисел (#501) стережёт заявленное от расхождения с прогоном. Вопрос,
ради которого заведена эта задача: насколько мелкое изменение физики она
обязана замечать -- и ответ на него до сих пор был «сколько-то», то есть
надежда.

## Отчего казалось, что она слепа

Приёмку #501 проверяли сломом: `_stimulate` стал ставить в очередь амплитуду
на 10% больше написанной --

    self._schedule(self.stim_synapses[stim.id], stim.amplitude * 1.10)

-- и весь набор прошёл целиком. Вывод напрашивался: проверка чисел не видит
изменения силы на десятую часть.

Вывод был неверный, и вот замер. Сила, поставленная в очередь, до клетки не
доходила вовсе: `_deliver` второе поле очереди отбрасывал и спрашивал силу
заново у `_release`. Умножение ломало мёртвое поле -- физика оставалась той
же, числа обязаны были сойтись, и они сходились. Поле убрано вместе с этой
задачей: `_schedule` ставит в очередь один синапс, а сила живёт в одном месте.

Сломанная же по-настоящему доставка корпусу видна. Если умножать на 10% то,
что возвращает `_release` стимульному синапсу, из 22 паттернов библиотеки
краснеют 15; на 1% -- 8. То есть проверка чисел не слепа.

## Зачем тогда зонд

Затем, что эти 15 из 22 -- случайность, а не обещание. Семь паттернов слома в
десятую часть не видят, и причина ровно та, что названа в задаче: драйв
бьёт в клетку-реле, а меряется выход за ней, и добавка к надпороговому удару
не двигает ни счёт спайков, ни момент разряда -- моменты квантованы шагом
`dt`. Стоит поправить любой из пятнадцати -- и чувствительность корпуса
изменится молча, потому что её никто не назвал числом.

Зонд ниже называет. Он устроен так, чтобы сила удара была видна непрерывно:

* драйв бьёт **прямо в измеряемую клетку**, без реле между ними;
* клетка **не разряжается** (порог недостижим) -- меряется не счёт спайков и
  не момент, а величина, которая двигается вместе с силой: пик `g_exc` и
  максимум `v`;
* допуск записан числом в самом зонде, а не «примерно».

Передача силы в пик проводимости здесь ровно один к одному: удар слабее на
процент -- пик ниже на процент. Поэтому `THRESHOLD` -- это одновременно и
доля, на которую должна измениться сила, и доля, на которую сдвинется
заявленное число.

## Почему рядом с тестами, а не в библиотеке

Дело паттерна библиотеки -- показывать механизм, и драйв через реле стоит там
по делу: он же защищает числа паттерна от дребезга. Переписать их под
чувствительность значило бы испортить корпус ради проверки корпуса. Зонд --
отдельная вещь: он ничего не показывает человеку и живёт здесь.
"""

from __future__ import annotations

import pytest

from vnl.expectations import check_model, failures
from vnl.resolve import load
from vnl.sim import lif, simulate

#: Изменение силы удара в эту долю и больше зонд обязан ловить.
#: 0.001 -- это одна десятая процента, и оба допуска зонда берут её с запасом:
#: допуск пика `g` (0.001 нСм при пике 2.0725 нСм) отвечает 0.048% силы, допуск
#: максимума `v` (0.005 мВ при сдвиге 0.0178 мВ на каждую десятую процента) --
#: 0.028%. То есть порог вдвое выше первого и втрое с лишним -- второго: он
#: обещание, а не край, на котором проверка держится чудом.
THRESHOLD = 0.001

#: Доля, на которой зонд молчать вправе. Проверяется с той же строгостью, что
#: и порог: допуск, съехавший вниз до последнего знака двоичной дроби, сделал
#: бы зонд дребезжащим, и его бы ослабили общим послаблением -- то есть сняли
#: бы разом со всех чисел.
QUIET = 0.0001

#: Зонд: один удар в клетку, которая его и меряет.
#:
#: Четыре импульса подряд, а не один: так в число входит и спад проводимости
#: между ударами, и подъём мембраны, то есть зонд стережёт не только высоту
#: одного скачка `g`, но и то, как считается время между ними.
PROBE = """
model stimulus_strength

# Порог недостижим: клетка копит и течёт, но не разряжается -- мерить можно
# величину, а не счёт целых спайков.
cell mute : excitatory, glutamate {
    tau_m      = 10ms
    threshold  = -20mV
    refractory = 4ms
}

neuron E : mute

stim drive -> E.soma : spikes weight=2nS times="20 25 30 35"

record E.soma.g_exc
record E.soma.v

expect {
    # Ноль спайков -- утверждение про сам зонд: подняв ему драйв, легко
    # получить разряды, и тогда `v.max` упрётся в порог, а чувствительность
    # исчезнет молча. Здесь это станет видно сразу.
    E.spikes = 0
    E.soma.g_exc.max = 2.0725nS tol=0.001nS
    E.soma.v.max     = -36.3123mV tol=0.005mV
}

run { dt = 0.1ms  duration = 80ms  level = L1  seed = 1 }
"""

#: Та же сила, но через реле и со счётом спайков -- устройство, которым
#: написана почти вся библиотека. Стоит здесь затем, чтобы разница зонда и
#: корпуса была видна замером, а не утверждалась на слово.
RELAY = """
model relay_blindness

cell relay : excitatory, glutamate {
    tau_m      = 8ms
    threshold  = -50mV
    refractory = 4ms
}

neuron IN : relay
neuron E  : relay

IN.soma -> E.soma { receptor = ampa  weight = 2.2nS  delay = 1.0ms }

stim drive -> IN.soma : spikes weight=3nS times="20 60 100 140 180 220 260 300"

record IN.soma.spikes
record E.soma.spikes

run { dt = 0.1ms  duration = 340ms  level = L1  seed = 1 }
"""


def build(text: str):
    model, diagnostics = load(text, source="probe.vnl", strict=True)
    errors = [str(d) for d in diagnostics if d.severity == "error"]
    assert not errors, errors
    return model


def break_stimulus(monkeypatch: pytest.MonkeyPatch, share: float) -> None:
    """Сломать солвер нарочно: удар стимула сильнее написанного на `share`.

    Ломается `_release` -- то самое место, которое решает, сколько
    проводимости придёт на клетку. Ломать очередь бесполезно: сила, стоявшая
    в ней вторым полем, была мёртвой, и с этой задачи её там нет вовсе.

    Достаётся только стимульным синапсам (`source is None`): так слом ровно
    тот, что описан в #577, и релейная схема ниже остаётся слепа к нему по
    своему устройству, а не потому, что её обошли стороной.
    """
    original = lif.Simulator._release

    def patched(self: lif.Simulator, synapse) -> float:
        value = original(self, synapse)
        return value * (1.0 + share) if synapse.source is None else value

    monkeypatch.setattr(lif.Simulator, "_release", patched)


def probe_failures() -> list[str]:
    return failures(check_model(build(PROBE)))


# --- зонд на целом солвере -------------------------------------------------


def test_the_probe_holds_its_numbers():
    """На нетронутом солвере зонд молчит -- иначе он не проверка, а шум."""
    assert probe_failures() == []


def test_the_probe_stays_subthreshold():
    """Клетка зонда не разряжается: мерить величину можно только пока так.

    То же сказано ожиданием `E.spikes = 0` внутри зонда; здесь -- отдельно,
    потому что от этого зависит смысл всех чисел ниже, а не одно из них.
    """
    assert simulate(build(PROBE)).spikes["E"] == []


# --- чувствительность, названная числом ------------------------------------


def test_ten_percent_is_caught_and_named(monkeypatch: pytest.MonkeyPatch):
    """Приёмка задачи: слом в десятую часть -- зонд падает и говорит, что разошлось."""
    break_stimulus(monkeypatch, 0.10)
    problems = probe_failures()
    assert problems, "слом в 10% обязан быть виден"

    text = "\n".join(problems)
    # Сообщение обязано называть и величину, и оба числа: «что-то разошлось»
    # стоит ровно столько же, сколько молчание.
    assert "E.soma.g_exc.max ожидалось 2.072nS, получено 2.280nS" in text, text
    assert "E.soma.v.max ожидалось -36.31mV, получено -34.60mV" in text, text


def test_one_percent_is_caught(monkeypatch: pytest.MonkeyPatch):
    """Решение по второй половине приёмки: на одном проценте зонд обязан падать.

    Один процент -- вдесятеро больше порога, и держать его незамеченным не за
    что: ниже проверено, что зонд при этом не дребезжит на ничтожных долях.
    Решение записано числом в `THRESHOLD`, а не словом «чувствительный».
    """
    break_stimulus(monkeypatch, 0.01)
    assert probe_failures(), "слом в 1% обязан быть виден"


def test_the_threshold_itself_is_caught(monkeypatch: pytest.MonkeyPatch):
    """Порог -- обещание, а не описание: на нём самом зонд обязан краснеть."""
    break_stimulus(monkeypatch, THRESHOLD)
    assert probe_failures(), f"порог {THRESHOLD:.3%} обязан ловиться"


def test_below_the_threshold_the_probe_keeps_quiet(monkeypatch: pytest.MonkeyPatch):
    """Зонд, краснеющий от всего, назавтра станет зондом с общим послаблением.

    Отсюда вторая граница: на доле вдесятеро меньше порога зонд молчит. Между
    `QUIET` и `THRESHOLD` не обещано ничего -- и это сказано вслух здесь,
    чтобы обещанием не считали середину.
    """
    break_stimulus(monkeypatch, QUIET)
    assert probe_failures() == []


# --- отчего слепнет корпус -------------------------------------------------


def test_a_relay_pattern_is_blind_to_one_percent(monkeypatch: pytest.MonkeyPatch):
    """Через реле слом в один процент не виден вовсе -- прогон побитово прежний.

    Это и есть причина, по которой зонд понадобился отдельно. Удар, ставший
    сильнее на сотую часть, всё так же надпороговый, а момент разряда квантован
    шагом `dt`: сдвинуть его добавка не может, и за реле не меняется ни одно
    число -- ни счёт, ни моменты. Тот же слом зонд ловит (см. выше).
    """
    honest = simulate(build(RELAY))

    break_stimulus(monkeypatch, 0.01)
    broken = simulate(build(RELAY))

    assert broken.spikes["IN"] == honest.spikes["IN"]
    assert broken.spikes["E"] == honest.spikes["E"]
    assert len(honest.spikes["E"]) == 8, "иначе слепота выше ничего не значит"


def test_a_relay_pattern_counts_the_same_at_ten_percent(
    monkeypatch: pytest.MonkeyPatch,
):
    """И на десятой части счёт спайков за реле не меняется -- сдвигается момент.

    Сдвиг ровно на один шаг `dt`, потому что меньше квант не позволяет. Отсюда
    и ступенчатая чувствительность корпуса: паттерн, заявивший счёт спайков,
    слома не увидит совсем, а заявивший первый спайк -- увидит или нет, смотря
    хватило ли добавки на целый шаг. Зонд не зависит ни от того, ни от другого:
    его числа двигаются непрерывно.
    """
    honest = simulate(build(RELAY))

    break_stimulus(monkeypatch, 0.10)
    broken = simulate(build(RELAY))

    assert len(broken.spikes["E"]) == len(honest.spikes["E"]) == 8
    shifts = {
        round(was - now, 6) for was, now in zip(honest.spikes["E"], broken.spikes["E"])
    }
    assert shifts == {0.1}, shifts
