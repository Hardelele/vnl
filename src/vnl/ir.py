@dataclass(frozen=True)
class Receptor:
    """Рецептор: числа, по которым его считают, и строка, по которой узнают.

    Строка живёт здесь, рядом с числами, по той же причине, что и единицы у
    `RecordedVariable`: `ampa` и `gaba_a` -- шифр, и расшифровать его может
    только тот, кто знает предмет (#541). Вторая таблица объяснений в браузере
    разошлась бы с этой незаметно -- и разошлась бы молча, потому что подсказка
    ни на один прогон не влияет и на тестах не всплыла бы.

    Чисел в тексте нет намеренно: реверсал и спад лежат рядом полями, их и
    показывают. Повтори их словами -- и правка `tau_decay` оставила бы в
    подсказке старое число.
    """

    #: мВ, потенциал, к которому синапс тянет клетку.
    reversal: float
    #: мс, за сколько спадает открытая проводимость.
    tau_decay: float
    #: Одна-две строки: чем этот рецептор отличается от соседнего по списку.
    note: str
    #: Снимается ли блок канала деполяризацией (#498). У NMDA -- да, и это не
    #: оттенок, а другой знак зависимости от потенциала: у всех остальных вклад
    #: с приближением к порогу убывает (множитель `E − v` тает), у NMDA растёт,
    #: потому что растущий `B(v)` его перебивает. Отсюда и берутся нелинейное
    #: совпадение входов и плато.
    voltage_dependent: bool = False
    #: мМ, внеклеточный магний -- он и есть та пробка, которую выбивает
    #: деполяризация. Читается только при `voltage_dependent`. Поле, а не
    #: константа в формуле: опыты с безмагниевым раствором -- обычное дело, и
    #: ноль здесь означает «блока нет», то есть NMDA как медленная AMPA.
    mg: float = 1.0

    def gate(self, v: float) -> float:
        """Какая доля открытой проводимости проводит при таком потенциале.

        Единица для всех рецепторов, кроме NMDA, -- и это не заглушка, а
        правда: обычный канал открыт настолько, насколько его открыл медиатор,
        и потенциал тут ни при чём. Ровная единица важна ещё и тем, что
        умножение на неё не может сдвинуть ни один прежний прогон.
        """
        if not self.voltage_dependent:
            return 1.0
        return mg_block(v, self.mg)


#: Порог показателя экспоненты в `mg_block`. Выше него `exp` переполняется, и в
#: трассе появляется `inf`, а потом `nan` -- то есть прогон молча превращается в
#: мусор. Зажим безопасен: при таком показателе блок и так закрыт наглухо
#: (`B < 1e-27`), и отличить зажатое от незажатого нечем.
_MG_EXP_CEILING = 64.0


def mg_block(v: float, mg: float = 1.0) -> float:
    """Множитель Джара--Стивенса: `1 / (1 + [Mg]/3.57 · exp(-0.062·v))`.

    Доля NMDA-каналов, из которых деполяризация вытолкнула ион магния. При
    -65 мВ и 1 мМ магния это 0.06 -- вход почти не проходит; при -20 мВ уже
    0.51. Растущий множитель перебивает убывающий `(E − v)`, эффективная
    проводимость растёт с деполяризацией, и появляется положительная обратная
    связь: чем сильнее клетка деполяризована, тем сильнее её деполяризует
    NMDA-вход.

    Формула однопараметрическая и стандартная (Jahr, Stevens 1990); числа
    0.062 и 3.57 -- из неё же и здесь не настраиваются. Настраивается магний:
    он живёт в растворе, а не в канале.

    Здесь, в ядре, а не в симуляторе: это знание предметной области ровно того
    же сорта, что реверсал рядом, и спрашивать его будет не только солвер --
    экспорт обязан сказать, что переносит не то.
    """
    if mg <= 0.0:
        # Магния нет -- выталкивать нечего, канал открыт целиком. Это не
        # вырожденный случай, а настоящий опыт: безмагниевый раствор -- то,
        # чем NMDA-ток и выделяют.
        return 1.0
    power = min(-0.062 * v, _MG_EXP_CEILING)
    return 1.0 / (1.0 + mg / 3.57 * math.exp(power))


