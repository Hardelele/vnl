# Тормозный рецептор определяется по реверсалу ниже потенциала покоя: именно
# он решает, тянет синапс клетку к порогу или от него.
INHIBITORY_RECEPTORS = frozenset(
    name for name, receptor in RECEPTORS.items() if receptor.reversal < -50.0
)


def is_inhibitory_receptor(receptor: str) -> bool:
    """Тормозный ли рецептор с таким именем -- по умолчанию реестра.

    Отвечает на вопрос об **имени**, а не о контакте: «что за белок `gaba_a` и
    чего от него ждут». Этого хватает там, где контакта ещё нет, -- список
    рецепторов в панели свойств, умолчание по медиатору, спор медиатора с
    рецептором (`receptor_disagrees`).

    Про конкретный контакт этого мало: с #496 реверсал пишется параметром, и
    `gaba_a` с `reversal = -65mV` ничего не тормозит -- он делит. Что контакт
    делает с той клеткой, на которой сидит, отвечает `synapse_polarity` -- по
    числу и с третьим исходом. Две функции здесь не дублируют друг друга: они
    отвечают на разные вопросы, и общего ответа у них нет по существу.
    """
    return receptor in INHIBITORY_RECEPTORS


#: Что контакт делает с клеткой. Три исхода, а не два, -- см. `synapse_polarity`.
POLARITY_EXC = "exc"
POLARITY_INH = "inh"
POLARITY_SHUNT = "shunt"

#: Полярности словами -- для подписей и сообщений. Здесь, а не у потребителя:
#: иначе «шунтирующий» в отчёте и в диагностике разошлись бы по формулировке.
POLARITY_NAMES: dict[str, str] = {
    POLARITY_EXC: "возбуждающий",
    POLARITY_INH: "тормозный",
    POLARITY_SHUNT: "шунтирующий",
}


def synapse_polarity(reversal: float, point: "PointModel") -> str:
    """Что контакт с таким реверсалом делает с такой клеткой (#496).

    Решается числом, а не именем рецептора, и ответов три.

    `inh` -- реверсал ниже покоя: открытая проводимость уводит мембрану от
    порога. Это вычитание, и его видно на `v`.

    `exc` -- реверсал не ниже порога: открытой проводимости, если её хватит,
    достаточно, чтобы клетка разрядилась сама по себе. Это то, что принято
    называть возбуждением.

    `shunt` -- между покоем и порогом: мембрану почти не двигает (при
    `E ≈ v_rest` слагаемое `g·(E − v)` у покоя равно нулю), а входное
    сопротивление клетки роняет, потому что `g` в знаменателе. Значит чужой
    вход делится, а не уменьшается на постоянную величину. Третий случай нужен
    именно потому, что ни одна из двух корзин про него не врёт наполовину: он
    не подводит к порогу и не уводит от него.

    Границы взяты по самой клетке, а не по общему для всех числу (-50 мВ, как
    у реестра `INHIBITORY_RECEPTORS`): у корзинчатой порог -52 мВ, у пирамиды
    -50, и один и тот же реверсал на них работает по-разному. Общая шкала
    врала бы ровно на том интервале, ради которого задача и делалась.

    Покой засчитан в шунт, а не в торможение (`reversal < v_rest`, не `<=`):
    канонический шунт -- это `E = v_rest`, и назвать его тормозным значило бы
    отправить в `g_inh` ту самую величину, ради разделения которой всё
    затевалось. Порог засчитан в возбуждение (`>= v_threshold`): на нём
    сравнение `v >= v_threshold` уже срабатывает, то есть клетка разряжается.
    """
    if reversal < point.v_rest:
        return POLARITY_INH
    if reversal >= point.v_threshold:
        return POLARITY_EXC
    return POLARITY_SHUNT


