@dataclass
class Expectation:
    """Заявленное число прогона, записанное в самой схеме (#501).

    Шапка `.vnl` утверждает результат словами и числом («выход пирамиды падает
    с 13 спайков до 6»). Комментарий не исполняется, поэтому такое утверждение
    может разойтись с движком и молчать об этом -- ровно это и случилось с
    #568, где неверными оказались числа восьми шапок сразу. `expect` -- то же
    утверждение, но машинное: живёт рядом с текстом, ревьюится вместе с ним и
    проверяется прогоном.

    Почему в `.vnl`, а не таблицей рядом с тестом. Таблица дешевле на день
    работы, но заводит второе место, где живут числа, и эти два места
    расходятся -- как расходятся всякое описание и то, что оно описывает.
    Здесь число стоит в том же файле, что и слова о нём, и правка одного без
    другого видна в диффе.
    """

    #: Имя величины: ключ `NEURON_MEASURES` или `TRACE_MEASURES`.
    measure: str
    #: Нейрон (для растровых величин) или ключ трассы `E.soma:g_exc`.
    target: str
    #: Заявленные числа в базовых единицах. Больше одного -- только у
    #: развёртки: там утверждение и есть ряд.
    values: tuple[float, ...] = ()
    #: Допуск в базовых единицах; у счёта спайков не используется -- спайки
    #: целые, и «почти столько же» про них ничего не значит.
    tolerance: float = 0.0
    #: Спецификация развёртки (`c3.weight=0,0.3,0.9`); пусто -- обычный прогон.
    sweep: str = ""
    #: Окно, в котором меряем: [start, stop). Половина заявленных чисел
    #: библиотеки -- про окно прогона, а не про весь прогон.
    start: float = 0.0
    stop: float = float("inf")
    #: Отсчёт, от которого считается величина: «отклик над покоем 5.00 мВ» --
    #: это `base = -65mV`. Без него в ожидании стояло бы -60.00, и число
    #: перестало бы совпадать с тем, что написано словами в шапке.
    base: float = 0.0
    #: Номер пика (для `peak`), с единицы.
    index: int = 1
    #: Уровень (для `time_above`).
    level: float = 0.0
    #: Как записано в файле -- для сообщения о расхождении.
    text: str = ""
    unit: str = ""
    #: Во сколько базовых единиц обходится одна написанная.
    factor: float = 1.0
    line: int = 0


@dataclass
class Model:
    name: str = "model"
    cell_types: dict[str, CellType] = field(default_factory=dict)
    instances: dict[str, Instance] = field(default_factory=dict)
    contacts: list[Contact] = field(default_factory=list)
    modulators: dict[str, Modulator] = field(default_factory=dict)
    stimuli: list[Stimulus] = field(default_factory=list)
    #: Граница с миром. Словарями по имени, как модуляторы: к сенсору ведёт
    #: подключение (`key -> MN.soma`), к мотору -- подача величины снаружи, и
    #: искать их по имени приходится на каждом шаге прогона.
    sensors: dict[str, Sensor] = field(default_factory=dict)
    motors: dict[str, Motor] = field(default_factory=dict)
    recordings: list[Recording] = field(default_factory=list)
    #: Заявленные числа прогона (#501). Часть демонстрации, а не конструкции:
    #: в чужую сеть блок их не везёт -- см. `Pattern.from_model`.
    expectations: list[Expectation] = field(default_factory=list)
    run: RunSpec = field(default_factory=RunSpec)
    source: str | None = None

    def cell_type_of(self, instance_id: str) -> CellType:
        return self.cell_types[self.instances[instance_id].cell_type]

    def morphology_of(self, instance_id: str) -> Morphology:
        return self.cell_type_of(instance_id).morphology

    def polarity_at(self, site: Site, reversal: float) -> str:
        """Что даст такой реверсал на клетке, которой принадлежит эта точка.

        Метод модели, а не свободная функция с тремя аргументами, потому что
        полярность спрашивают из шести мест (отчёт, DOT, ответ сервера,
        диагностика, запись, экспорт), и каждому пришлось бы самому доставать
        точечную модель постсинаптической клетки. Шесть одинаковых цепочек
        `cell_types[instances[site.instance].cell_type].point_model` -- это
        шесть мест, где однажды возьмут не ту клетку.
        """
        return synapse_polarity(
            reversal, self.cell_type_of(site.instance).point_model
        )

    def polarity_of(self, contact: Contact) -> str:
        """Что контакт делает с клеткой, на которой сидит: exc | inh | shunt."""
        return self.polarity_at(contact.post, contact.reversal)

    def summary(self) -> dict[str, Any]:
        return {
            "cell_types": len(self.cell_types),
            "instances": len(self.instances),
            "contacts": len(self.contacts),
            "modulators": len(self.modulators),
            "stimuli": len(self.stimuli),
            "sensors": len(self.sensors),
            "motors": len(self.motors),
            "recordings": len(self.recordings),
        }
