def point_model_problems(point: PointModel) -> list[str]:
    """Чем эта мембрана посчитается не тем, чем выглядит.

    Один список на всех, кто спрашивает: разбор файла (`resolve`) и правка
    мембраны в песочнице (`Project.set_cell`). До #527 правил было два набора
    -- у разбора полный, у песочницы три имени в `CELL_POSITIVE`, -- и это не
    придирка к порядку: на холсте собиралось то, чего файл потом не принимал,
    а узнавал об этом человек уже на сохранении.

    Живёт здесь по той же причине, по которой здесь живёт `v_discharge`:
    спрашивают с двух сторон, и вторая копия разошлась бы с первой молча.

    Возвращается список строк, а не поднимается исключение: у разбора своя
    дорога для ошибок (`Diagnostic` с адресом места в файле), у правки своя
    (`PatternError` в панель свойств), и выбирать между ними здесь не из чего.

    Только отказы. Предупреждение -- это про то, что посчитается, но не так,
    как человек, скорее всего, думал; разбору его сказать есть куда, а правке
    одного поля некуда, и отказывать по нему нельзя.
    """
    if point.kind not in POINT_MODELS:
        known = ", ".join(POINT_MODELS)
        return [
            f"точечная модель {point.kind!r} не реализована (есть: {known}); "
            "считать её как другую значило бы молча подменить физику"
        ]
    if point.kind != "adex":
        return []

    # Каждая проверка ловит случай, где уравнение остаётся считаемым, но
    # перестаёт быть тем, что человек описал. Молчать про такое хуже, чем
    # отказать: получится числовой ответ, по которому нельзя догадаться, что
    # спросили не то.
    problems: list[str] = []
    if point.delta_t <= 0.0:
        problems.append(
            f"delta_t = {point.delta_t:g} мВ: резкость разгона обязана быть "
            "положительной, иначе экспоненциального члена нет вовсе и клетка "
            "сводится к lif с порогом на v_peak"
        )
    if point.tau_w <= 0.0:
        problems.append(
            f"tau_w = {point.tau_w:g} мс: постоянная тока адаптации обязана "
            "быть положительной, иначе ток ничего не помнит и ни пачки, ни "
            "отдачи из него не получится"
        )
    if point.v_peak <= point.v_threshold:
        problems.append(
            f"v_peak = {point.v_peak:g} мВ не выше v_t = {point.v_threshold:g} мВ: "
            "разряд признавался бы раньше, чем начинается разгон, и "
            "экспоненциальный член никогда не заработал бы"
        )
    if point.v_reset >= point.v_peak:
        problems.append(
            f"v_reset = {point.v_reset:g} мВ не ниже v_peak = {point.v_peak:g} мВ: "
            "после сброса клетка сразу выше потенциала разряда и будет "
            "разряжаться до конца прогона независимо от входа; для пачки "
            "v_reset ставят между v_t и v_peak"
        )
    return problems


