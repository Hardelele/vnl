"""Роды драйва и протоколы стимуляции: шаблон разворачивается в список времён.

Здесь живёт один реестр родов драйва -- и тех трёх, что были (`current`,
`poisson`, `spikes`), и шаблонов протоколов (#508). Реестр один нарочно: для
человека «чем я бью по схеме» -- один вопрос, а два списка (один в Python, один
в браузере) уже разошлись бы, потому что подпись ни на один прогон не влияет и
на тестах прогона расхождение не всплывает.

**Шаблон -- сахар над `spikes`, а не замена.** Любой протокол обязан уметь
напечатать себя списком времён (`spike_times`), и именно этот список идёт в
солвер, в экспорт, в отчёт и в тест. Отсюда и главное требование к
воспроизводимости: `train { n = 8, freq = 50Hz, start = 50ms }` и написанный
руками `spikes times = "50 70 90 110 130 150 170 190"` -- это один и тот же
прогон до последнего разряда, потому что до солвера доходит один и тот же
кортеж чисел.

Разобранная альтернатива: разворачивать шаблон прямо при разборе `.vnl`, то
есть превращать `train` в `spikes` ещё в резолвере. Тогда IR не пришлось бы
трогать вовсе. Отказались по двум причинам. Первая -- отчёт: от протокола
остался бы список из пятидесяти чисел, а сказать «поезд, 8 импульсов, 20 Гц,
тест восстановления через 500 мс» стало бы нечем, хотя именно этими словами
эксперимент и называется. Вторая -- правка: в песочнице человек правит `n` и
`freq`, а не пятьдесят чисел, и стимул, развёрнутый при загрузке, обратно в
поезд уже не сворачивается.

Имена параметров взяты у PyNN и NeuroML, а не выдуманы: `amplitude`, `rate`,
`start`/`stop`/`duration`, `freq`, `isi`, `n`. Где у них есть готовое имя,
своего здесь нет.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, Callable

#: Сколько импульсов позволено одному шаблону. Ограничение житейское, как и
#: `SAMPLE_LIMIT` у прогона: `tetanus freq=1000Hz duration=60s` -- это опечатка,
#: а не эксперимент, и отвечать на неё надо сообщением, а не минутой ожидания.
MAX_TIMES = 10_000

#: До скольких знаков округляются времена. 1000/3 Гц даёт 333.3333333333333, и
#: без округления список времён нельзя ни прочитать, ни сравнить глазами с
#: написанным руками `spikes`. Шесть знаков -- заведомо мельче любого шага
#: интегрирования (`dt` = 0.1 мс), то есть на попадание импульса в шаг
#: округление не влияет.
ROUND = 6


class ProtocolError(ValueError):
    """Шаблон нельзя развернуть: параметры не складываются в список времён."""


# --- чистые функции разворачивания ----------------------------------------
#
# Каждая принимает только числа и возвращает только времена: протокол
# проверяется как арифметика, отдельно от IR, песочницы и солвера.


def _count(name: str, value: Any) -> int:
    number = int(value)
    if number < 1:
        raise ProtocolError(f"{name} должно быть не меньше 1, а не {value!r}")
    return number


def _positive(name: str, value: Any) -> float:
    number = float(value)
    if number <= 0:
        raise ProtocolError(f"{name} должно быть больше нуля, а не {value!r}")
    return number


def _repeat(
    episode: list[float], start: float, repeats: int, period: float
) -> tuple[float, ...]:
    """Повторить эпизод `repeats` раз через `period` и сдвинуть на `start`.

    Один повтор -- это просто сдвиг: эпизод, записанный от нуля, кладётся в
    абсолютное время здесь и только здесь, чтобы `start` не пришлось помнить
    каждому шаблону отдельно.
    """
    times = _count("repeats", repeats)
    if times > 1 and float(period) <= 0:
        raise ProtocolError(
            "повторов эпизода несколько, а period не задан: без интервала "
            "между эпизодами они легли бы один на другой"
        )
    out = [
        round(float(start) + index * float(period) + moment, ROUND)
        for index in range(times)
        for moment in episode
    ]
    if len(out) > MAX_TIMES:
        raise ProtocolError(
            f"шаблон даёт {len(out)} импульсов, больше {MAX_TIMES}: "
            f"похоже на опечатку в частоте или длительности"
        )
    return tuple(out)


def train(
    *,
    n: int = 8,
    freq: float = 20.0,
    start: float = 0.0,
    recovery: float = 0.0,
    repeats: int = 1,
    period: float = 0.0,
) -> tuple[float, ...]:
    """Регулярный поезд: `n` импульсов с частотой `freq`.

    `recovery` -- тестовый импульс через столько миллисекунд после последнего
    импульса поезда. Он не украшение: 8 импульсов на 20 Гц истощают ресурс
    контакта, а одиночный тест через 500 мс меряет, сколько ресурса вернулось,
    то есть отделяет `tau_rec` от снижения вероятности выброса. Ноль значит
    «теста нет» -- отдельного флага для этого не заводится, потому что тест
    через ноль миллисекунд после поезда и есть отсутствие теста.
    """
    count = _count("n", n)
    step = 1000.0 / _positive("freq", freq)
    episode = [index * step for index in range(count)]
    if float(recovery) > 0:
        episode.append(episode[-1] + float(recovery))
    return _repeat(episode, start, repeats, period)


def pairs(
    *, n: int = 1, isi: float = 50.0, freq: float = 10.0, start: float = 0.0
) -> tuple[float, ...]:
    """Парная стимуляция: две посылки через `isi`, `n` пар с частотой `freq`.

    `freq` здесь -- частота повторения пар (`pair_rate` в карточке), а не
    частота внутри пары: внутри пары расстояние задаёт `isi`, и второго имени
    для того же «как часто» заводить незачем.
    """
    count = _count("n", n)
    gap = _positive("isi", isi)
    if count == 1:
        # Одна пара -- самый частый случай (PPR меряется одной парой), и
        # требовать для неё частоту повторения значило бы просить число,
        # которое ни на что не влияет.
        return _repeat([0.0, gap], start, 1, 0.0)
    return _repeat([0.0, gap], start, count, 1000.0 / _positive("freq", freq))


def burst(*, n: int = 4, freq: float = 100.0, start: float = 0.0) -> tuple[float, ...]:
    """Пачка: `n` импульсов с внутрипачечной частотой `freq`.

    Арифметика та же, что у поезда, и это честно: пачка -- это короткий поезд.
    Отдельный род оставлен ради двух вещей, которые от арифметики не зависят.
    Первая -- числа по умолчанию: 4 импульса по 100 Гц, ровно та пачка, из
    которых собран theta-burst (Larson & Lynch, 1986), и набирать их руками
    каждый раз незачем. Вторая -- отчёт: «пачка 4×100 Гц» и «поезд 8×20 Гц»
    описывают разные эксперименты, и одно слово на оба читалось бы как ошибка.
    """
    return train(n=n, freq=freq, start=start)


def tetanus(
    *, freq: float = 100.0, duration: float = 1000.0, start: float = 0.0
) -> tuple[float, ...]:
    """Тетанус: частота `freq` в течение `duration`."""
    step = 1000.0 / _positive("freq", freq)
    window = _positive("duration", duration)
    # 100 Гц в течение 1000 мс -- это 100 импульсов (0 … 990), а не 101:
    # длительность -- окно стимуляции, а не расстояние до последнего импульса.
    # Иначе тетанус длиной в ровно один период давал бы два импульса.
    count = int(math.floor(window / step + 1e-9))
    if count < 1:
        raise ProtocolError(
            f"за {window:g} мс при {freq:g} Гц не помещается ни одного импульса"
        )
    return _repeat([index * step for index in range(count)], start, 1, 0.0)


def theta_burst(
    *,
    n: int = 4,
    freq: float = 100.0,
    bursts: int = 10,
    burst_period: float = 200.0,
    repeats: int = 1,
    period: float = 0.0,
    start: float = 0.0,
) -> tuple[float, ...]:
    """Theta-burst: пачки по `n` импульсов, пачка каждые `burst_period`.

    Уровней здесь три, и у каждого своя пара имён: импульсы в пачке (`n`,
    `freq`), пачки в эпизоде (`bursts`, `burst_period`), эпизоды (`repeats`,
    `period`). Пара `repeats`/`period` значит «эпизод» у всех шаблонов
    одинаково -- поэтому средний уровень и получил собственные имена, а не
    перегрузил чужие.
    """
    inside = burst(n=n, freq=freq)
    count = _count("bursts", bursts)
    if count > 1:
        _positive("burst_period", burst_period)
    episode = [
        index * float(burst_period) + moment
        for index in range(count)
        for moment in inside
    ]
    return _repeat(episode, start, repeats, period)


# --- реестр родов драйва ---------------------------------------------------


@dataclass(frozen=True)
class Param:
    """Параметр рода драйва: и поле стимула, и поле панели свойств.

    `name` -- имя поля `ir.Stimulus`/`SandboxStimulus` и одновременно ключ, под
    которым значение уходит обратно в `PATCH .../stimuli/<id>`. Таблицы
    перевода имён между сервером и браузером нет намеренно: это было бы третье
    место, где протокол описан, и разошлось бы оно молча.
    """

    name: str
    label: str
    unit: str = ""
    default: float = 0.0
    step: float = 1.0
    #: number -- дробное число, int -- счётное, times -- список моментов.
    form: str = "number"
    note: str = ""


@dataclass(frozen=True)
class DriveKind:
    """Род драйва: как он зовётся, что значит и какими числами задаётся."""

    id: str
    name: str
    note: str
    params: tuple[Param, ...]
    #: Нужен ли этому роду рецептор. У тока его нет: ток входит в клетку
    #: помимо синапса, и предлагать выбрать для него `ampa` значило бы
    #: спрашивать то, что никуда не пойдёт.
    receptor: bool = True
    #: Разворачивание в список времён. `None` -- у родов, у которых списка нет
    #: (ток) или он задан руками (`spikes`).
    expand: Callable[[Any], tuple[float, ...]] | None = None
    #: Протокол словами -- для отчёта прогона и подписи на таймлайне.
    story: Callable[[Any], str] = lambda stim: stim.kind


def _amplitude(label: str, unit: str, default: float, note: str) -> Param:
    return Param(
        name="amplitude",
        label=label,
        unit=unit,
        default=default,
        step=0.1,
        note=note,
    )


