def _call(fn: Callable[..., tuple[float, ...]], stim: Any, *names: str) -> tuple[float, ...]:
    """Позвать чистую функцию полями стимула. `start` общий у всех родов."""
    return fn(start=stim.start, **{name: getattr(stim, name) for name in names})


def _plural(count: int, one: str, few: str, many: str) -> str:
    """«8 импульсов», «1 импульс», «2 импульса» -- отчёт читают люди."""
    tail = count % 100
    last = count % 10
    if 11 <= tail <= 14 or last == 0 or last >= 5:
        return f"{count} {many}"
    return f"{count} {one}" if last == 1 else f"{count} {few}"


def _impulses(count: int) -> str:
    return _plural(count, "импульс", "импульса", "импульсов")


def _bursts(count: int) -> str:
    return _plural(count, "пачка", "пачки", "пачек")


def _episodes(stim: Any) -> str:
    if int(stim.repeats) <= 1:
        return ""
    episodes = _plural(int(stim.repeats), "эпизод", "эпизода", "эпизодов")
    return f", {episodes} через {float(stim.period):g} мс"


def _train_story(stim: Any) -> str:
    out = f"поезд, {_impulses(int(stim.n))}, {float(stim.freq):g} Гц"
    if float(stim.recovery) > 0:
        out += f", тест восстановления через {float(stim.recovery):g} мс"
    return out + _episodes(stim)


def _pairs_story(stim: Any) -> str:
    out = f"пары, интервал {float(stim.isi):g} мс"
    if int(stim.n) > 1:
        out += f", {int(stim.n)} пар с частотой повторения {float(stim.freq):g} Гц"
    return out


