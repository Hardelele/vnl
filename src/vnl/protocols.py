def defaults(kind: str) -> dict[str, Any]:
    """Канонические числа рода: чем он заводится, если ничего не сказано.

    Живут в реестре, а не в полях датакласса, потому что у одного и того же
    поля они разные: `n` -- это 8 у поезда и 4 у пачки, и одно значение по
    умолчанию на оба поле не описывает. Применяются в двух местах, где стимул
    рождается: при разборе `.vnl` и при смене рода в песочнице.

    Формы стимула -- `amplitude` и `times` -- сюда не попадают нарочно. Вес
    драйва человек ставит под свою схему и при смене рода терять его не
    должен, а подставлять вместо набранных моментов пустоту тем более незачем:
    здесь числа только те, которыми задана сама форма протокола.
    """
    drive = DRIVE_KINDS.get(kind)
    if drive is None:
        return {}
    return {
        param.name: (int(param.default) if param.form == "int" else param.default)
        for param in drive.params
        if param.form != "times" and param.name != "amplitude"
    }


#: Все числа, которыми задаётся форма протокола, -- объединением по всем родам.
#: Нужно там, где параметры принимают пачкой и не знают заранее рода: HTTP
#: принимает `{"n": 8, "freq": 20}` и обязан понять, что `n` счётное, а `freq`
#: дробное. Значения здесь -- образцы типа, а не значения по умолчанию: за
#: умолчаниями ходят в `defaults`, где они зависят от рода.
SHAPE: dict[str, Any] = {
    name: value for kind in TEMPLATES for name, value in defaults(kind).items()
}


def spike_times(stim: Any) -> tuple[float, ...]:
    """Список моментов стимула: написанный руками или развёрнутый из шаблона.

    Единственное место, где протокол превращается в числа. Солвер, экспорт,
    отчёт и панель свойств зовут отсюда -- второй разворот тех же параметров
    разошёлся бы с этим на первой же правке, и разошёлся бы молча: список
    времён нигде не печатается целиком.
    """
    drive = DRIVE_KINDS.get(stim.kind)
    if drive is None or drive.expand is None:
        return tuple(float(time) for time in getattr(stim, "times", ()))
    return drive.expand(stim)


def describe(stim: Any) -> str:
    """Протокол словами: «поезд, 8 импульсов, 20 Гц, тест через 500 мс».

    Отчёт прогона называет эксперимент так, как его называет человек, а не
    списком чисел: пятьдесят чисел в подписи не читаются, а «раз в 10 мс»
    читается. Сам список при этом никуда не девается -- он рядом, в `times`.
    """
    drive = DRIVE_KINDS.get(stim.kind)
    if drive is None:
        return str(stim.kind)
    return drive.story(stim)


#: Выше какой частоты повторения пар честного ответа от VNL ждать нельзя.
#: Знак STDP в опыте зависит не только от Δt, но и от частоты повторения пар:
#: при 0.1 Гц выходит только LTD при любом порядке спайков, при 40-50 Гц --
#: только LTP, тоже при любом (Sjöström, Turrigiano & Nelson, 2001). Ядро
#: W(Δt) с парой `a_plus`/`a_minus`, которое реализовано в `sim/lif.py`,
#: воспроизвести это не может в принципе -- ни при каких значениях. Значит,
#: выше примерно этой частоты модель расходится с экспериментом качественно,
#: а не количественно, и молчать об этом нельзя: человек получит красивое
#: число, которое ничего не значит.
STDP_SAFE_RATE = 25.0


def cautions(model: Any) -> list[str]:
    """Протоколы, на которых движку верить нельзя. Не отказ, а предупреждение.

    Отказывать нечестно: считать-то движок считает, и посмотреть на результат
    человек вправе. Молчать нечестнее: разница с опытом тут не в третьем знаке,
    а в знаке самого изменения веса.

    Правильное лечение -- тройное или потенциал-зависимое правило вместо
    фиксированного ядра, а не подбор `a_plus`; это отдельная задача.
    """
    if not any(contact.plasticity.enabled for contact in model.contacts):
        return []
    out: list[str] = []
    for stim in model.stimuli:
        if stim.kind != "pairs" or int(stim.n) <= 1:
            continue
        if float(stim.freq) <= STDP_SAFE_RATE:
            continue
        out.append(
            f"стимул {stim.id}: пары повторяются {float(stim.freq):g} Гц, а "
            f"выше {STDP_SAFE_RATE:g} Гц знак STDP в опыте задаёт частота "
            "повторения, а не порядок спайков (Sjöström, Turrigiano & Nelson, "
            "2001). Фиксированное ядро W(Δt) этого не воспроизводит ни при "
            "каких a_plus: честный диапазон -- 10-20 Гц."
        )
    return out


# --- роды сенсора и мотора --------------------------------------------------
#
# Здесь же, а не в своём модуле, нарочно -- и это то же решение, по которому
# роды драйва лежат одним списком. Для человека «чем сеть связана с миром» --
# один вопрос, и отвечать на него обязано одно место: род хранит свои
# параметры (`Param` -- тот же, что у драйва), объясняет себя словами и умеет
# превратить величину в то, что увидит клетка. Второй реестр рядом с этим
# означал бы вторую таблицу подписей, вторые умолчания и второе правило «какие
# числа тут осмысленны» -- и разошлись бы они молча, потому что подпись ни на
# один прогон не влияет.
#
# Разобранная альтернатива: считать сенсор разновидностью драйва и дописать его
# в `DRIVE_KINDS`. Отказались: у драйва моменты известны заранее (в том и смысл
# протокола -- поставить повторимый опыт), а у сенсора их не знает никто, пока
# снаружи не подадут величину. Свести их в один список значило бы объявить, что
# `train { n = 8 }` и «кнопку нажали» -- одно и то же, и каждому потребителю
# родов пришлось бы спрашивать «а этот род вообще разворачивается в времена».

#: Границы величины, которая приходит снаружи. Ноль -- «не действует», единица
#: -- «действует в полную силу»; всё между ними осмысленно, и род сам решает,
#: что с этим делать. Шкала выбрана безразмерной, потому что за дверью может
#: стоять что угодно -- кнопка, ползунок, датчик, -- и переводить их единицы в
#: наносименсы обязан сенсор, а не тот, кто подаёт.
VALUE_MIN = 0.0
VALUE_MAX = 1.0


class SenseError(ValueError):
    """Величину нельзя принять: не тот сенсор или не то число."""


def check_value(value: Any) -> float:
    """Величина, пришедшая снаружи. Отказ, а не зажим.

    Зажать 5 в единицу значило бы принять заведомо чужую шкалу и промолчать:
    подающий считает, что подал пять, а сеть увидела один, и разницу нигде не
    видно. Кнопка на 0/1 попадает в границы сама, а аналоговый вход обязан
    договориться о шкале до первого значения, а не после неудачного опыта.
    """
    try:
        number = float(value)
    except (TypeError, ValueError) as error:
        raise SenseError(f"величина сенсора -- число, а не {value!r}") from error
    if not VALUE_MIN <= number <= VALUE_MAX:
        raise SenseError(
            f"величина сенсора {number:g} вне {VALUE_MIN:g}…{VALUE_MAX:g}: "
            "через границу идёт безразмерная доля силы, а не сами герцы"
        )
    return number


def _rate_events(
    sensor: Any, value: float, previous: float, phase: float, dt: float
) -> tuple[int, float]:
    """Уровень -> ровный поток: `to` герц при величине 1, ноль при нуле.

    Фаза копится по долям периода, и каждый её оборот -- один импульс. Так
    сделано, чтобы поток не зависел от шага интегрирования: при 100 Гц и
    `dt = 0.1` мс импульс выходит ровно раз в сто шагов, а не «на каждом шаге с
    вероятностью». Случайность здесь была бы лишней: за дверью и так стоит
    человек, а повторить нажатие в точности нужно обязательно.

    Фаза -- состояние, и она обязана попадать в снимок симулятора, ровно как
    состояние генератора случайных чисел: иначе откат времени сдвинул бы весь
    поток на долю периода и повтор разошёлся бы с исходным прогоном.
    """
    freq = max(0.0, float(value)) * float(sensor.to)
    phase += freq * float(dt) / 1000.0
    count = int(phase)
    return count, phase - count


def _rate_read(motor: Any, spikes: Any, now: float) -> float:
    """Разряды за окно -> частота в герцах.

    Наружу идёт частота, а не доля от чего-то: «сколько это много» -- свойство
    опыта, а не мотора, и нормировать здесь было бы нечем. Тому, кто зажигает
    лампочку, хватает вопроса «ненулевая ли», а тому, кто меряет, нужна
    величина в единицах, которые он узнает.

    Окно -- скользящее и смотрит только назад: разряды, которых ещё не было,
    мотор видеть не может, и именно поэтому величина мотора повторяется при
    откате сама собой -- она целиком считается по уже записанному растру.
    """
    window = float(motor.window)
    if window <= 0:
        return 0.0
    # Полуинтервал (now - window, now]: разряд на самой границе принадлежит
    # прошлому окну, иначе он посчитался бы дважды в соседних окнах.
    edge = float(now) - window
    count = sum(1 for time in spikes if edge < time <= float(now) + 1e-9)
    return count / (window / 1000.0)


@dataclass(frozen=True)
class SensorKind:
    """Род сенсора: как он зовётся, что значит и во что превращает величину."""

    id: str
    name: str
    note: str
    params: tuple[Param, ...]
    #: На что род отвечает: `level` -- на удерживаемую величину («держат
    #: единицу -- идёт поток»), `change` -- на её перемену («нажали»,
    #: «отпустили»). Поле объявлено сразу, хотя род пока один: событийный род
    #: обязан быть возможен без переделки реестра, и отличается он ровно этим.
    #: Тот, кто показывает сенсор человеку, по этому полю и объясняет разницу.
    trigger: str = "level"
    #: Чем род действует на клетку: `events` -- импульсами через синапс,
    #: `current` -- током помимо синапса. У токового рода рецептора нет, как и
    #: у драйва `current`, -- предлагать его значило бы спрашивать то, что
    #: никуда не пойдёт.
    emits: str = "events"
    receptor: bool = True
    #: Сколько импульсов дать на этом шаге и с какой фазой остаться. Величина
    #: приходит и нынешняя, и прошлая: роду уровня хватает первой, роду
    #: изменения нужна пара. `None` -- род не событийный (ток).
    events: Callable[[Any, float, float, float, float], tuple[int, float]] | None = None
    #: Род словами -- для отчёта прогона и подписи в интерфейсе.
    story: Callable[[Any], str] = lambda sensor: sensor.kind


