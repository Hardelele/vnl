/**
 * Список моментов одной строкой.
 *
 * Нужен с тех пор, как драйв можно задать шаблоном протокола (#508): тетанус
 * 100 Гц в течение секунды -- это сто моментов, и выписать их подряд значит
 * залить ими всю панель. Но и спрятать нельзя: шаблон обязан уметь напечатать
 * себя списком времён, иначе «поезд» остаётся таким же словом на веру, каким
 * был «пуассоновский».
 *
 * Поэтому середина: начало списка видно целиком, последний момент показан
 * отдельно -- по этим двум концам видно и шаг, и куда протокол дотягивается.
 * Считать шаг за человека здесь нельзя: у пачек он внутри один, между пачками
 * другой, и «каждые 10 мс» было бы враньём ровно там, где протокол интереснее
 * всего.
 */

import { MOMENTS, counted } from './plural'

/** Сколько моментов выписывается подряд, прежде чем список сворачивается. */
const SHOWN = 8

export function momentList(times: number[]): string {
  if (!times.length) return ''
  if (times.length <= SHOWN + 1) return times.join(', ')
  return `${times.slice(0, SHOWN).join(', ')} … ${times[times.length - 1]}`
}

/** «50 моментов: 0, 10, 20 … 490 мс». Пусто -- когда моментов нет вовсе. */
export function momentWords(times: number[]): string {
  if (!times.length) return ''
  return `${counted(times.length, MOMENTS)}: ${momentList(times)} мс`
}
