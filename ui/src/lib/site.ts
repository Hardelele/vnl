/**
 * Точка на клетке одной строкой: `E.soma`, `E.dend.apical[1]@0.6`.
 *
 * Отдельно от экранов, потому что адрес пишут в трёх местах витрины -- строка
 * связи, выбранная связь, драйв и записи, -- и написан он обязан быть одинаково.
 * Разойдись они, `@0.6` стояло бы в одном списке и пропадало в другом, а речь
 * об одной и той же точке.
 *
 * Середина участка (`0.5`) не пишется: это умолчание и в языке, и в NEURON, а
 * `@0.5` у каждой второй строки -- шум, за которым не видно тех мест, где доля
 * выбрана нарочно.
 */

import type { Site } from '../model/types'

export function siteText(site: Site): string {
  const tail = site.fraction === 0.5 ? '' : `@${site.fraction}`
  return `${site.instance}.${site.section}${tail}`
}
