/**
 * Знак на конце связи: чем она кончается там, куда приходит.
 *
 * Одно описание на весь проект. Раньше их было три: миниатюра каталога и
 * начинка блока рисовали остриё 6.5 и плашку 4.5, повёрнутые по касательной;
 * холст песочницы -- остриё 6 и плашку 4, повёрнутые поперёк хода; схема
 * карточки -- кружок и плашку. Владелец увидел это прежде всех прочих
 * расхождений: «и стрелки по-другому нарисованы» (#554).
 *
 * Числа взяты библиотечные. Направление переноса выбрано владельцем прямо: в
 * библиотеке читается хорошо, значит остальные места подгоняются под неё, а не
 * она под них.
 *
 * Знак рода, а не размера. Он не растёт вместе с фигурой: его задача -- сказать
 * «возбуждение» или «торможение», и на клетке холста высотой 38 он должен
 * читаться так же, как на клетке миниатюры высотой 20. Растяни его по фигуре --
 * и одна и та же связь выглядела бы разной силы в двух местах.
 *
 * Возбуждение -- остриё, а не точка. Точка симметрична и о направлении не
 * говорит: `A→B` и `B→A` выглядели одинаково, и по этой причине её убрали из
 * миниатюры ещё в #524. На большой схеме точка значит место контакта на ветви,
 * но ветвей нет ни в песочнице, ни на карточке -- там все связи в сому, -- и
 * точка на конце оставалась ровно двусмысленностью. Появятся ветви -- точка
 * вернётся дополнением к линии, а не знаком её конца.
 *
 * Торможение -- плашка поперёк, модуляция -- то же остриё, но линия янтарная и
 * пунктирная (род рисуется цветом и пунктиром, `is-mod` в стилях).
 */

export interface MarkPoint {
  x: number
  y: number
}

/** Длина острия. Больше -- знак закрывает саму связь. */
export const TIP = 6.5
/** Половина плашки торможения. */
export const CAP = 4.5
/** Половина ширины острия у основания: при 3 остриё узкое и не читается кружком. */
const TIP_HALF = 3

/**
 * Остриё на конце связи -- точки многоугольника для SVG.
 *
 * `tip` -- единичный вектор входа в цель, касательная в конце кривой. Именно
 * касательная, а не направление «начало -- конец»: на дуге это разные вещи, и
 * знак, повёрнутый по второму, смотрел бы мимо клетки.
 */
export function tipPoints(end: MarkPoint, tip: MarkPoint): string {
  const ux = tip.x
  const uy = tip.y
  return [
    `${end.x},${end.y}`,
    `${end.x - ux * TIP - uy * TIP_HALF},${end.y - uy * TIP + ux * TIP_HALF}`,
    `${end.x - ux * TIP + uy * TIP_HALF},${end.y - uy * TIP - ux * TIP_HALF}`,
  ].join(' ')
}

/** Плашка торможения -- отрезок поперёк хода связи в её конце. */
export function capLine(
  end: MarkPoint,
  tip: MarkPoint,
): { x1: number; y1: number; x2: number; y2: number } {
  const ux = tip.x
  const uy = tip.y
  return {
    x1: end.x - uy * CAP,
    y1: end.y + ux * CAP,
    x2: end.x + uy * CAP,
    y2: end.y - ux * CAP,
  }
}
