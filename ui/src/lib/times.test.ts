import { describe, expect, it } from 'vitest'

import { momentList, momentWords } from './times'

describe('список моментов одной строкой', () => {
  it('короткий список виден целиком', () => {
    expect(momentList([50, 70, 90])).toBe('50, 70, 90')
  })

  it('длинный сворачивается, но оба конца остаются', () => {
    // Тетанус 100 Гц в течение секунды -- сто моментов: выписать их подряд
    // значит залить ими панель, а спрятать -- оставить «поезд» словом на веру.
    const times = Array.from({ length: 100 }, (_, index) => index * 10)
    expect(momentList(times)).toBe('0, 10, 20, 30, 40, 50, 60, 70 … 990')
  })

  it('числительное согласовано с числом моментов', () => {
    expect(momentWords([10])).toBe('1 момент: 10 мс')
    expect(momentWords([10, 20])).toBe('2 момента: 10, 20 мс')
    expect(momentWords([10, 20, 30, 40, 50])).toBe('5 моментов: 10, 20, 30, 40, 50 мс')
  })

  it('моментов нет -- нет и строки', () => {
    // У пуассоновского драйва моментов заранее не бывает вовсе, и «0 моментов»
    // было бы не фактом, а придиркой к роду стимула.
    expect(momentWords([])).toBe('')
  })
})
