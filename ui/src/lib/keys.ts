/**
 * Клавиши экрана: одно правило на всех, кто слушает `keydown` на окне.
 *
 * Слушателей таких два -- транспорт времени (стрелки шагают по прогону, #537)
 * и песочница (`Delete` убирает выбранное, Ctrl+D дублирует, #563), -- и оба
 * обязаны молчать в одном и том же случае: когда человек набирает текст.
 * Второе определение «набирают ли сейчас» разошлось бы с первым молча: в поле
 * имени клетки `Delete` стирает букву, и отбирать его у поля нельзя, а
 * заметно это стало бы только на жалобе «стёр символ -- исчезла клетка».
 */

/** Набирают ли сейчас текст: тогда клавиша принадлежит полю, а не экрану. */
export function typing(target: EventTarget | null): boolean {
  const node = target as HTMLElement | null
  if (!node || !node.tagName) return false
  if (node.isContentEditable) return true
  return ['INPUT', 'TEXTAREA', 'SELECT'].includes(node.tagName)
}

/**
 * Чужое ли это сочетание -- такое, в которое лезть не за чем.
 *
 * `Alt` и одиночный `Shift` с клавишами экрана не спорят, а вот `Ctrl`/`Cmd`
 * спорит: им в браузере копируют, сохраняют и ходят по вкладкам. Поэтому
 * каждый слушатель говорит про `Ctrl` отдельно -- транспорт его пропускает
 * мимо (#537), песочница на `Ctrl+D` наоборот откликается, -- а общего здесь
 * только то, что событие уже разобрал кто-то другой.
 */
export function handled(event: KeyboardEvent): boolean {
  return event.defaultPrevented || event.altKey
}

/** Что клавиша просит сделать с выбранным объектом песочницы (#563). */
export type ObjectCommand = 'remove' | 'duplicate' | null

/**
 * Разбор нажатия над выбранным объектом.
 *
 * Отдельной функцией, а не внутри обработчика: правила тут не механические --
 * какие клавиши наши, чья это раскладка, что дублируется, а что нет, -- и
 * проверять их удобнее прямо, а не через отрисованный экран.
 *
 * `kind` -- род выбранного (`block`, `neuron`, `link`, `stimulus`,
 * `recording`) или `null`, когда не выбрано ничего. Строкой, а не типом
 * выделения: правила про клавиши живут ниже состояния песочницы и знать о нём
 * не должны.
 *
 * Что здесь решено:
 *
 * - `Delete` и `Backspace` -- одно и то же. Отдельного `Delete` может не быть
 *   на клавиатуре вовсе (ноутбуки, Mac), и оставить только его значило бы
 *   отдать половине людей удаление только через панель свойств.
 * - Дублируется объект холста -- блок или клетка. У связи копия не получила
 *   бы второго конца, а у стимула цель одна: копия била бы в ту же клетку
 *   вторым входом, то есть дала бы другую схему, а не второй такой же объект.
 * - Ctrl+D, а не Ctrl+C/Ctrl+V: перехват копирования отнял бы привычное
 *   «скопировать имя клетки в текст», а буфер из одного объекта был бы вторым,
 *   невидимым местом, где лежит кусок проекта, -- с вопросами, что с ним
 *   после отмены и после перехода в другой проект.
 * - Смотрится `code`, а не `key`: на русской раскладке та же клавиша шлёт `в`,
 *   и сочетание не работало бы ровно у того, кто читает эту панель по-русски.
 * - Со стрелками (#537) и Ctrl с колесом (#548) спора нет: те заняты временем
 *   и приближением, а тут другие клавиши.
 */
export function objectCommand(
  event: KeyboardEvent,
  kind: string | null,
): ObjectCommand {
  if (handled(event) || typing(event.target) || !kind) return null
  if (event.ctrlKey || event.metaKey) {
    if (event.code !== 'KeyD') return null
    return kind === 'block' || kind === 'neuron' ? 'duplicate' : null
  }
  return event.key === 'Delete' || event.key === 'Backspace' ? 'remove' : null
}

/**
 * Клавиша кнопки песочницы (#562): её `code` или `null`, если клавиша не наша.
 *
 * Кнопку жмут мышью, а клавиша -- второй способ сделать то же самое: нажал --
 * подали 1, отпустил -- 0. Поэтому разбор один на `keydown` и на `keyup`:
 * два правила разъехались бы ровно в том случае, ради которого всё и делается
 * -- клавишу зажали одним правилом, а отпустили другим, и сенсор остался бы
 * нажатым навсегда.
 *
 * Берутся только буквы и цифры, и это не бедность списка, а разведение с
 * занятым: стрелки шагают по времени (#537), `Delete` и Ctrl+D правят объект
 * на холсте (#563), Ctrl с колесом приближает холст (#548). Закрытый список
 * «буквы и цифры» разводит с ними раз и навсегда -- перечислять же запретное
 * значило бы дописывать сюда строку после каждой новой клавиши экрана и
 * узнавать о пропуске от человека, у которого кнопка «съела» шаг по времени.
 *
 * Сочетания не берутся вовсе: Ctrl и Cmd заняты браузером и холстом, а
 * Shift+буква -- это заглавная, то есть та же клавиша. `repeat` отбрасывается
 * здесь же: автоповтор зажатой клавиши шлёт `keydown` полсотни раз в секунду,
 * и каждое из них стало бы отдельной записью в поданном -- вход, который
 * человек считает одним нажатием, в записи был бы сотней.
 */
export function boardKey(event: KeyboardEvent): string | null {
  if (handled(event) || typing(event.target)) return null
  if (event.ctrlKey || event.metaKey || event.repeat) return null
  return /^(Key[A-Z]|Digit[0-9])$/.test(event.code) ? event.code : null
}

/**
 * Клавиша словами: `KeyA` -> `A`, `Digit1` -> `1`.
 *
 * Показывается латиница, а не то, что напечатает клавиша в текущей раскладке:
 * держимся мы за `code`, то есть за место клавиши, и подпись обязана говорить
 * про то же самое. «Ф» на кнопке, которая работает от клавиши `A`, была бы
 * правдой ровно до переключения раскладки.
 */
export function keyLabel(code: string): string {
  return code.replace(/^Key|^Digit/, '')
}
