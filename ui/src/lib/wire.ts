/**
 * Провод между объектами холста песочницы.
 *
 * Рисуется тем же подбором дуги, что и связь в миниатюре: `arc` из
 * `lib/miniature`. Своей кривой здесь больше нет.
 *
 * Как дошло до своей. Сперва сторона была прибита к роли конца: источник
 * отдавал справа, цель принимала слева, а кривая строилась с управляющими
 * точками `start.x + bend` и `end.x - bend`. Это верно ровно в одном случае --
 * когда цель правее источника; как только цель левее, провод обязан был выйти
 * вправо, развернуться и прийти слева, то есть обогнуть оба узла снаружи. В
 * схеме с возвратом такова половина связей, и холст превращался в клубок. В
 * #542 сторону стали выбирать по взаимному расположению концов, и петля ушла.
 *
 * Почему этого оказалось мало. Изображений одной и той же схемы в проекте было
 * три -- строка библиотеки, холст и карточка, -- и они разошлись во всём:
 * места клеток, форма кривой, знаки на концах. Человек видел внутри коробки
 * схему слоями, жал «разобрать на клетки» и получал ту же схему сеткой, да ещё
 * и другими кривыми. Владелец назвал эталон прямо: «сделай так, чтобы то, что
 * было в библиотеке, было и на доске, тк в библиотеке хорошо! Не наоборот»
 * (#554). Поэтому холст взял библиотечную дугу, а не наоборот.
 *
 * Библиотечная дуга ту же беду #542 решает иначе и без единого условия про
 * «назад». Ей вообще не из чего выбирать сторону: связь выходит и входит там,
 * где граница фигуры смотрит на выбранный изгиб, а изгиб выбирается перебором
 * по штрафу -- задел за чужую фигуру, выход за поле, лишняя кривизна. Связь
 * справа налево получает такую же короткую дугу, что и прямая, просто
 * зеркальную; механизма, который заставлял её обходить узлы снаружи, здесь
 * нет вовсе. Разведение встречных связей (#524) достаётся тем же приёмом:
 * перпендикуляр берётся справа по ходу, у встречной ход обратный, и дуги
 * расходятся сами.
 *
 * Что холсту всё-таки нужно сверх миниатюры, и почему это не вторая кривая:
 *
 * - **поле**. У миниатюры оно своё и начинается в нуле, у холста это общий
 *   прямоугольник схемы: фигуры стоят там, куда их положил человек. Поле --
 *   довод функции `arc`, а не её вторая настройка;
 * - **связь на себя** (`relay4 → relay4`). Оба конца в одной точке: ход
 *   нулевой длины, делить на него нельзя, изгибать нечего. Миниатюра такие
 *   связи не рисует вовсе (в схеме паттерна их не бывает), а на холсте они
 *   есть, и им нужна петля у самой фигуры -- случай, а не другая кривая;
 * - **порт**. Порт нарисован кружком на своём краю коробки, и провод обязан
 *   прийти ровно туда. Отдельной ветки это не требует: у порта нулевые
 *   полуразмеры, и точка на границе такой фигуры -- она сама.
 */

import { arc, type ArcBox, type ArcField, type MiniPoint } from './miniature'

export type Point = MiniPoint

/**
 * Конец провода: фигура, к которой он крепится.
 *
 * У клетки и внутреннего узла это их прямоугольник, у порта -- точка: нулевые
 * полуразмеры. Сторону подхода никто не задаёт: её задаёт изгиб дуги.
 */
export interface WireEnd {
  /** Центр фигуры. */
  x: number
  y: number
  halfWidth: number
  halfHeight: number
}

/**
 * Что вокруг связи. Всё необязательно: одна связь между двумя фигурами
 * рисуется и без окружения -- просто прямой, если та никому не мешает.
 */
export interface WirePlace {
  /** Чужие фигуры: дуга обязана пройти мимо них, а не сквозь. */
  others?: ArcBox[]
  /** Общий прямоугольник схемы -- за него дуге лучше не выходить. */
  field?: ArcField
  /** Сколько связей уже прошло этим же ходом: вторая идёт дугой пошире. */
  sameWay?: number
  /** Единственная ли это связь между парой концов: одинокая может идти прямой. */
  alone?: boolean
}

/** Как проложен провод. Имя случая видно в разметке и в тестах. */
export type WireShape = 'arc' | 'self'

export interface Wire {
  start: Point
  end: Point
  /** Единичный вектор входа в цель: по нему повёрнут знак на конце связи. */
  tip: Point
  /** Путь для SVG: та же кривая, что и у полосы попадания мышью. */
  path: string
  shape: WireShape
  /** Отклонение дуги от прямой; 0 -- связь идёт прямой. */
  bow: number
}

/**
 * Вынос петли «на себя» за край фигуры. Примерно половина клетки: меньше --
 * петля читается как утолщение обводки, больше -- лезет на соседа, который в
 * песочнице стоит в полутора сотнях пикселей.
 */
const LOOP = 36

/** Запас поля вокруг фигур, когда общий прямоугольник схемы не передали. */
const FIELD_MARGIN = 60

function round(value: number): number {
  return Math.round(value * 100) / 100
}

function box(end: WireEnd): ArcBox {
  return {
    x: end.x,
    y: end.y,
    width: end.halfWidth * 2,
    height: end.halfHeight * 2,
  }
}

/**
 * Связь клетки на себя.
 *
 * Уходит вправо и возвращается сверху: обе точки на одной фигуре, и сойтись
 * они могут только в обход. Правый край выбран потому же, почему там нарисована
 * сома, -- связь читается слева направо, -- а верхний потому, что снизу у
 * клетки ничего не написано, а сверху стоит её заряд, и петля над ним видна.
 */
function selfWire(end: WireEnd): Wire {
  const start = { x: end.x + end.halfWidth, y: end.y }
  const stop = { x: end.x, y: end.y - end.halfHeight }
  const first = { x: start.x + LOOP, y: start.y }
  const second = { x: stop.x + LOOP, y: stop.y - LOOP }
  const dx = stop.x - second.x
  const dy = stop.y - second.y
  const length = Math.hypot(dx, dy) || 1
  return {
    start,
    end: stop,
    tip: { x: dx / length, y: dy / length },
    path: [
      `M ${round(start.x)} ${round(start.y)}`,
      `C ${round(first.x)} ${round(first.y)},`,
      `${round(second.x)} ${round(second.y)},`,
      `${round(stop.x)} ${round(stop.y)}`,
    ].join(' '),
    shape: 'self',
    bow: LOOP,
  }
}

/**
 * Общий прямоугольник вокруг фигур с запасом -- поле для дуг.
 *
 * Оно же приёмка #542 словами: «ни один провод не выходит за общий
 * прямоугольник схемы дальше, чем на свой изгиб». У миниатюры поле задано
 * макетом карточки, а на холсте его задают сами фигуры -- их кладёт человек.
 */
export function schemeField(boxes: ArcBox[]): ArcField {
  let left = Infinity
  let top = Infinity
  let right = -Infinity
  let bottom = -Infinity
  for (const item of boxes) {
    left = Math.min(left, item.x - item.width / 2)
    top = Math.min(top, item.y - item.height / 2)
    right = Math.max(right, item.x + item.width / 2)
    bottom = Math.max(bottom, item.y + item.height / 2)
  }
  return {
    x: left - FIELD_MARGIN,
    y: top - FIELD_MARGIN,
    width: right - left + FIELD_MARGIN * 2,
    height: bottom - top + FIELD_MARGIN * 2,
  }
}

/** Провод от одного конца к другому. */
export function wire(from: WireEnd, to: WireEnd, place: WirePlace = {}): Wire {
  const dx = to.x - from.x
  const dy = to.y - from.y
  // Ровно одна точка на двоих: связь на себя. Дальше пришлось бы делить на
  // нулевую длину хода, а изгибать нечего.
  if (Math.abs(dx) < 1e-6 && Math.abs(dy) < 1e-6) return selfWire(from)

  const head = box(from)
  const tail = box(to)
  const others = place.others ?? []
  const field = place.field ?? schemeField([head, tail, ...others])
  const line = arc(
    head,
    tail,
    others,
    field,
    place.sameWay ?? 0,
    place.alone ?? true,
  )
  return {
    start: line.start,
    end: line.end,
    tip: line.tip,
    path: [
      `M ${round(line.start.x)} ${round(line.start.y)}`,
      `Q ${round(line.control.x)} ${round(line.control.y)}`,
      `${round(line.end.x)} ${round(line.end.y)}`,
    ].join(' '),
    shape: 'arc',
    bow: line.bow,
  }
}
