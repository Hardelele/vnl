/**
 * Провод между объектами холста песочницы.
 *
 * Прежде сторона была прибита к роли конца: источник отдавал справа, цель
 * принимала слева, а кривая строилась с управляющими точками `start.x + bend`
 * и `end.x - bend`. Это верно ровно в одном случае -- когда цель правее
 * источника. Как только цель левее, управляющие точки расходятся в разные
 * стороны, и провод обязан выйти вправо, развернуться и прийти слева, то есть
 * обогнуть оба узла снаружи. В схеме с возвратом такова половина связей, и
 * холст превращался в клубок.
 *
 * Здесь сторона выбирается по взаимному расположению концов: провод уходит с
 * той стороны фигуры, которая смотрит на второй конец, и приходит с той,
 * которая смотрит на первый. Тогда возврат рисуется такой же короткой дугой,
 * что и прямая связь, только зеркальной.
 *
 * Три случая названы отдельно, потому что одной формулой они не берутся:
 *
 * - **поперёк** (`across`) -- узлы стоят рядом по горизонтали, дуге нужен
 *   горизонтальный изгиб; это обычная связь слева направо и такой же возврат
 *   справа налево;
 * - **вдоль** (`along`) -- узлы стоят друг над другом, и горизонтальный изгиб
 *   здесь бесполезен: он уводит линию вбок и обратно, рисуя ту же петлю в
 *   миниатюре. Дуга изгибается по вертикали;
 * - **на себя** (`self`) -- начало и конец в одной точке. Кривая между
 *   совпавшими точками вырождается в ничто, а прежняя формула давала кольцо
 *   через весь холст. Рисуется петля у самой клетки.
 *
 * Величина изгиба берётся не от расстояния по модулю, а от проекции хода на
 * направление выхода. У связи «назад» проекция при правильно выбранной стороне
 * такая же, как у прямой, -- дуга той же величины. А там, где сторона задана
 * жёстко и провод всё-таки обязан завернуть (порт блока сам на себя), проекция
 * отрицательна, и изгиб остаётся наименьшим: петля не раздувается тем сильнее,
 * чем длиннее возврат.
 *
 * Сам возврат вдобавок отводится дугой в сторону. Без отвода он идёт по тому же
 * коридору, что и прямые связи цепочки, и на ряду клеток одной высоты ложится
 * точно на них -- связь есть, а увидеть её нельзя. Сторона отвода та же, что у
 * дуг миниатюры: перпендикуляр справа по ходу связи.
 *
 * Это не вторая `miniature`: та раскладывает начинку блока на поле со
 * спичечный коробок и сама выбирает отклонение дуги, обходя чужие фигуры. Здесь
 * места концов заданы человеком, фигуры крупные, и вопрос стоит только про
 * сторону подхода.
 */

export interface Point {
  x: number
  y: number
}

/** Сторона фигуры, к которой крепится провод. */
export type Side = 'left' | 'right' | 'top' | 'bottom'

/**
 * Конец провода: фигура, к которой он крепится.
 *
 * `side` заполнен у порта: порт -- названная автором дверь, нарисованная на
 * своём краю коробки (входы слева, выходы справа), и провод обязан приходить
 * именно туда, иначе он оторвётся от кружка порта. У клетки и внутреннего узла
 * двери нет вовсе -- есть сома, -- и сторону выбирает расположение.
 */
export interface WireEnd {
  /** Центр фигуры. */
  x: number
  y: number
  halfWidth: number
  halfHeight: number
  side?: Side
}

/** Как проложен провод. Имя случая видно в разметке и в тестах. */
export type WireShape = 'across' | 'along' | 'self'

export interface Wire {
  start: Point
  end: Point
  /** Единичный вектор входа в цель: по нему повёрнут знак на конце связи. */
  tip: Point
  /** Путь для SVG: та же кривая, что и у полосы попадания мышью. */
  path: string
  shape: WireShape
  exit: Side
  entry: Side
}

/**
 * Наименьший изгиб. Меньше -- и у близких соседей провод выходит из фигуры
 * почти прямым отрезком, а две связи между соседними узлами сливаются в одну
 * линию.
 */
const MIN_BEND = 30

/**
 * Вынос петли «на себя» за край фигуры. Примерно половина клетки: меньше --
 * петля читается как утолщение обводки, больше -- лезет на соседа, который в
 * песочнице стоит в полутора сотнях пикселей.
 */
const LOOP = 36

/**
 * Отвод дуги в сторону от прямой. Кривая отходит от неё на три четверти
 * отвода, то есть на 36, -- ровно мимо клетки высотой 38.
 */
const BOW = 48

const NORMAL: Record<Side, Point> = {
  left: { x: -1, y: 0 },
  right: { x: 1, y: 0 },
  top: { x: 0, y: -1 },
  bottom: { x: 0, y: 1 },
}

const OPPOSITE: Record<Side, Side> = {
  left: 'right',
  right: 'left',
  top: 'bottom',
  bottom: 'top',
}

/** Точка на краю фигуры с выбранной стороны. У порта полуразмеры нулевые. */
function attach(end: WireEnd, side: Side): Point {
  const normal = NORMAL[side]
  return {
    x: end.x + normal.x * end.halfWidth,
    y: end.y + normal.y * end.halfHeight,
  }
}

/**
 * Сторона, смотрящая на второй конец.
 *
 * Вертикаль выбирается, когда ход вверх-вниз длиннее хода вбок. Сравнивать с
 * полуразмерами фигур (мол, клетка низкая и широкая, и сто пикселей по
 * вертикали -- это дальше, чем сто по горизонтали) заманчиво, но тогда сторона
 * зависела бы ещё и от длины имени клетки: ширину фигуры задаёт подпись.
 * Связь меняла бы направление от переименования узла -- хуже, чем неточность у
 * диагонали, где читаются оба варианта.
 */
function facing(dx: number, dy: number): Side {
  if (Math.abs(dy) > Math.abs(dx)) return dy > 0 ? 'bottom' : 'top'
  return dx > 0 ? 'right' : 'left'
}

/** Направление единичной длины. Нулевой ход сюда не доходит: он -- связь на себя. */
function unit(x: number, y: number): Point {
  const length = Math.hypot(x, y) || 1
  return { x: x / length, y: y / length }
}

function round(value: number): number {
  return Math.round(value * 100) / 100
}

function curve(start: Point, first: Point, second: Point, end: Point): string {
  return [
    `M ${round(start.x)} ${round(start.y)}`,
    `C ${round(first.x)} ${round(first.y)},`,
    `${round(second.x)} ${round(second.y)},`,
    `${round(end.x)} ${round(end.y)}`,
  ].join(' ')
}

/**
 * Связь клетки на себя.
 *
 * Уходит вправо и возвращается сверху: обе точки на одной фигуре, и сойтись
 * они могут только в обход. Правый край выбран потому же, почему там нарисована
 * сома, -- связь читается слева направо, -- а верхний потому, что снизу у
 * клетки ничего не написано, а сверху стоит её заряд, и петля над ним видна.
 */
function selfWire(end: WireEnd): Wire {
  const start = attach(end, 'right')
  const stop = attach(end, 'top')
  const first = { x: start.x + LOOP, y: start.y }
  const second = { x: stop.x + LOOP, y: stop.y - LOOP }
  return {
    start,
    end: stop,
    tip: unit(stop.x - second.x, stop.y - second.y),
    path: curve(start, first, second, stop),
    shape: 'self',
    exit: 'right',
    entry: 'top',
  }
}

/** Провод от одного конца к другому. */
export function wire(from: WireEnd, to: WireEnd): Wire {
  const dx = to.x - from.x
  const dy = to.y - from.y
  // Ровно одна точка на двоих: связь на себя. Дальше пришлось бы делить на
  // нулевую длину хода, а сторону выбирать не из чего.
  if (Math.abs(dx) < 1e-6 && Math.abs(dy) < 1e-6) return selfWire(from)

  const aside = facing(dx, dy)
  const exit = from.side ?? aside
  const entry = to.side ?? OPPOSITE[aside]
  // Связь идёт против чтения схемы -- слева направо и сверху вниз. Это и есть
  // «возврат»: сторона, с которой она уходит, сама об этом и говорит.
  const backward = aside === 'left' || aside === 'top'
  const start = attach(from, exit)
  const end = attach(to, entry)

  const out = NORMAL[exit]
  const into = NORMAL[entry]
  const runX = end.x - start.x
  const runY = end.y - start.y
  // Ход по направлению стороны. У выбранной по расположению стороны он
  // положителен всегда -- она для того и выбрана; отрицательным он бывает у
  // порта, чья сторона задана жёстко и смотрит не туда, куда идёт связь.
  const outRun = runX * out.x + runY * out.y
  const inRun = -runX * into.x - runY * into.y
  // Половина хода -- ровно то, чем изгиб был и раньше у прямой связи, так что
  // привычные связи слева направо выглядят как выглядели. От модуля расстояния
  // он больше не считается: у возврата модуль тот же, а знак был другой, и
  // петля раздувалась тем сильнее, чем длиннее возврат.
  const outBend = Math.max(MIN_BEND, outRun / 2)
  const inBend = Math.max(MIN_BEND, inRun / 2)

  // Прямо связь идти не может в двух случаях, и оба лечатся отводом в сторону.
  //
  // Возврат идёт по тому же коридору, что и прямые связи цепочки, и на ряду
  // клеток, стоящих на одной высоте, ложится точно на них: связь есть, а
  // увидеть её нельзя. Вторая -- та, у которой обе стороны заданы жёстко и обе
  // смотрят не туда (выход блока в его же вход): её управляющие точки лежат на
  // одной линии с концами, и кривая вырождается в отрезок по самой коробке.
  //
  // Сторона отвода -- перпендикуляр справа по ходу связи, как у дуг миниатюры:
  // у встречной пары ход обратный, и дуги расходятся сами, без сговора между
  // связями и без зависимости от порядка в списке.
  const stuck = outRun < 0 && inRun < 0
  const length = Math.hypot(runX, runY) || 1
  const bow = backward || stuck ? BOW : 0
  const swayX = (-runY / length) * bow
  const swayY = (runX / length) * bow

  const first = {
    x: start.x + out.x * outBend + swayX,
    y: start.y + out.y * outBend + swayY,
  }
  const second = {
    x: end.x + into.x * inBend + swayX,
    y: end.y + into.y * inBend + swayY,
  }

  return {
    start,
    end,
    // Кривая входит в цель из последней управляющей точки: по этому же ходу
    // повёрнут и знак на её конце.
    tip: unit(end.x - second.x, end.y - second.y),
    path: curve(start, first, second, end),
    // Случай называется по взаимному расположению узлов, а не по выбранным
    // сторонам: у порта сторона задана жёстко, и связь в порт снизу всё равно
    // остаётся связью «вдоль».
    shape: aside === 'top' || aside === 'bottom' ? 'along' : 'across',
    exit,
    entry,
  }
}
