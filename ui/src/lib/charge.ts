/**
 * Заряд клетки как надпись: доля -> проценты.
 *
 * Доля приходит из сессии (`CellState.charge`): покой -- 0, порог -- 1, ниже
 * покоя -- отрицательная. Здесь она только превращается в то, что читает глаз,
 * и ничего не пересчитывается: физика считается один раз, на сервере.
 *
 * Отдельным файлом, потому что надпись нужна в двух местах -- над клеткой на
 * схеме и в инспекторе выбранной клетки, -- и «33%» в них обязано быть одним и
 * тем же числом. Разойдись округление, и человек увидел бы 33% на схеме и 34%
 * в панели про ту же клетку в тот же момент.
 */

/** Надпись о заряде: что написать и не увели ли клетку ниже покоя. */
export interface ChargeLabel {
  /** Готовый текст: `33%`, `100%`, `↓18%`. */
  text: string
  /** Клетка ниже покоя -- надпись красится в цвет торможения. */
  below: boolean
}

/**
 * Надпись по доле заряда. `null` -- состояния клетки нет (сессия ещё не
 * ответила), и писать нечего: `0%` в этом месте был бы выдумкой.
 */
export function chargeLabel(charge: number | undefined | null): ChargeLabel | null {
  if (charge === null || charge === undefined || !Number.isFinite(charge)) return null
  // Округляем до целых процентов. Сессия отвечает несколько раз в секунду, и
  // десятые доли в такой смене читаются как дрожание цифр, а не как величина:
  // «33.7%» и «33.4%» в соседних кадрах говорят об одном и том же. Целый
  // процент -- наименьшее, что вообще различимо на глаз, и меняется он ровно
  // тогда, когда на экране действительно что-то изменилось.
  const percent = Math.round(charge * 100)
  // Знак берётся от округлённого числа, а не от доли: -0.004 -- это 0%, и
  // писать при нём «ниже покоя» значило бы пугать шумом последнего знака.
  const below = percent < 0
  // Ниже покоя отмечено стрелкой, а не минусом: минус в надписи над клеткой
  // стоит рядом с цифрами и в таком кегле почти не виден, а стрелка читается,
  // не разглядывая. Цвет торможения на ней -- вторым признаком того же.
  return { text: below ? `↓${-percent}%` : `${percent}%`, below }
}

/**
 * Что показать про клетку в этом кадре.
 *
 * Между двумя кадрами движок делает полсотни шагов, а разряд занимает один:
 * спрашивая мгновенное значение, разряд видишь с вероятностью доли процента --
 * то есть никогда, и клетка на схеме никогда не доходит до ста процентов, хотя
 * в движке доходит каждый раз. Поэтому в кадре, где разряд был, показывается
 * то, до чего клетка дошла (`peak`), а не то, где она оказалась после сброса.
 *
 * Правило живёт здесь, а не в каждом месте показа: схема и инспектор обязаны
 * говорить об одной клетке одно и то же.
 */
export function momentOf(state: {
  charge: number
  peak?: number
  spiked?: boolean
} | null | undefined): number | null {
  if (!state) return null
  if (state.spiked && typeof state.peak === 'number') return Math.max(state.peak, 1)
  return state.charge
}
