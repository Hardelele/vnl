/**
 * Встроенные образцы: что можно показать полю, ничего не загружая (#581).
 *
 * Список приходит от сервера (`vnl.samples`), а не лежит здесь: растры букв
 * живут в пакете, их же читает `tools/letters.py`, и второй набор, записанный
 * в браузере, разошёлся бы с первым молча — «T» на экране перестала бы быть
 * той «T», про которую написаны числа в примерах.
 *
 * Сами кадры сюда не едут. Их 36 по 576 величин, то есть двадцать тысяч чисел
 * ради выпадающего списка; выбранный образец показывается полю по имени —
 * прямо в сессию, минуя браузер (`showSim`).
 */

import { request } from './catalog'

export interface SampleInfo {
  /** Имя образца: то же, что пишут в `tools/letters.py T`. */
  id: string
  /** Строк и столбцов. */
  grid: [number, number]
  /** Сколько величин в кадре ненулевые — по этому числу и узнают букву. */
  lit: number
}

export function readSamples(): Promise<SampleInfo[]> {
  return request<{ samples: SampleInfo[] }>('/api/samples').then(
    (answer) => answer.samples,
  )
}
