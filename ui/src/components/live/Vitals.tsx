/**
 * Живое состояние одной клетки: заряд, потенциал и разряды за прогон.
 *
 * Отдельным файлом, потому что об этом спрашивают в двух рабочих местах --
 * в инспекторе карточки паттерна и в панели свойств песочницы, -- а ответ
 * обязан быть один. Разойдись они, человек читал бы на витрине «54%», а про ту
 * же клетку в тот же момент в песочнице -- «53%» или вовсе один потенциал в
 * милливольтах, из которого доли до порога не вычислить: порог у клетки свой,
 * и адаптация поднимает его выше номинального.
 *
 * Ни одно из трёх чисел здесь не считается заново. Долю считает сессия
 * (`CellState.charge`), потенциал приходит оттуда же, разряды -- список их
 * моментов. Частота берётся по пройденному времени симуляции, а не по
 * длительности прогона: на середине прогона делить на полную длительность
 * значило бы показывать вдвое меньшую частоту и пугать ею зря.
 *
 * Сетка та же, что у параметров мембраны в инспекторе (`insp-grid`): заряд
 * отвечает на главный вопрос о клетке сейчас и занимает строку целиком,
 * потенциал и разряды делят вторую.
 */

import { chargeLabel, momentOf } from '../../lib/charge'
import type { CellState } from '../../model/sim'
import './inspector.css'

export interface VitalsProps {
  /** Состояние клетки из сессии. Пусто -- сессия ещё не отвечала про неё. */
  state: CellState | undefined
  /** Моменты разрядов этой клетки за прогон, мс. */
  spikes: number[]
  /** Пройденное время симуляции, мс. */
  elapsed: number
}

export function Vitals({ state, spikes, elapsed }: VitalsProps) {
  // Тот же процент, что стоит над клеткой на схеме и на холсте: одна функция,
  // одно округление -- иначе фигура и панель разошлись бы на единицу в том же
  // кадре. Правило кадра (`momentOf`) тоже общее: в кадре разряда показан пик,
  // а не то, где клетка оказалась после сброса.
  const level = chargeLabel(momentOf(state))
  const rate = elapsed > 0 ? (spikes.length / elapsed) * 1000 : 0
  return (
    <div className="insp-grid">
      {/* Заряд первым и во всю ширину: он отвечает на главный вопрос о клетке
          сейчас -- далеко ли ей до разряда. */}
      <Field
        label="заряд"
        value={level ? (level.below ? `${level.text} · ниже покоя` : level.text) : '—'}
        wide
        below={level?.below}
      />
      <Field label="потенциал" value={state ? `${state.v.toFixed(1)} мВ` : '—'} />
      {/* Пока сессии нет, разрядов не «ноль», а неизвестно: пустой список
          спайков у незапущенной схемы и у молчащей клетки -- разные вещи, и
          «0 · 0 Гц» в первом случае читался бы как ответ про клетку. */}
      <Field
        label="разряды"
        value={state ? `${spikes.length} · ${rate.toFixed(0)} Гц` : '—'}
      />
    </div>
  )
}

/**
 * Ячейка сетки: подпись и значение.
 *
 * Здесь, а не в инспекторе, потому что ею набраны обе сетки -- живые числа и
 * параметры мембраны, -- и вторая такая же ячейка разъехалась бы с первой по
 * отступам при первой же правке.
 */
export function Field({
  label,
  value,
  wide = false,
  below = false,
  hint,
}: {
  label: string
  value: string
  /** Во всю ширину сетки: так стоит заряд, остальное -- половинками. */
  wide?: boolean
  /** Клетка ниже покоя: значение красится в цвет торможения, как на схеме. */
  below?: boolean
  /**
   * Расшифровка подписи из словаря сервера (#541, #546). Стоит на всей ячейке,
   * а не на одном значении: спрашивают и «что такое вес», и «что такое
   * gaba_a», -- а это подпись и значение одной и той же ячейки.
   */
  hint?: string
}) {
  return (
    <div className={`insp-cell${wide ? ' is-wide' : ''}`} title={hint}>
      <span className="insp-label">{label}</span>
      <span className={`mono insp-value${below ? ' is-below' : ''}`}>{value}</span>
    </div>
  )
}
