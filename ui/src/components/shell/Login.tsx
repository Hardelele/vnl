/**
 * Подпись со ссылкой на вход.
 *
 * Только для отказов, которых никто не просил: каталог читается сам, и уводить
 * с экрана человека, ничего не нажимавшего, нельзя. Отказ на нажатую кнопку
 * ведёт ко входу сразу (`goToLogin`) -- окно с вопросом «войти?» было бы лишним
 * шагом перед тем же переходом.
 *
 * Своего экрана и полей логина здесь нет намеренно: пароль, введённый в
 * интерфейсе, пришлось бы куда-то отправлять, то есть стенд снова знал бы
 * чужие пароли. Отсюда уходит только ссылка -- и именно ссылка, а не `fetch`:
 * вход это цепочка редиректов браузера, и запрос из скрипта её не пройдёт.
 */

import './shell.css'

export interface LoginHintProps {
  /** Что случилось или что закрыто -- своими словами, без «ошибка 401». */
  children: React.ReactNode
  /** Адрес шага входа на сервере. */
  login: string
}

/** Строка рядом с тем, что человек нажал. */
export function LoginHint({ children, login }: LoginHintProps) {
  return (
    <p className="need" role="alert">
      <span className="need-text">{children}</span>
      <a className="need-go" href={login}>
        Войти
      </a>
    </p>
  )
}
