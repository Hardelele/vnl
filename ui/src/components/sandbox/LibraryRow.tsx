/**
 * Строка библиотеки в песочнице: превью схемы, имя и вставка.
 *
 * Раньше строка была одноэтажной: миниатюра 60x30 слева, имя справа с
 * многоточием. Миниатюра при этом рисовала верную схему -- просто в размере,
 * где ни один её признак не различим: скруглённая фигура переставала
 * отличаться от квадратной, острие от плашки, подписи клеток не читались
 * вовсе. Получались «три точки», по которым паттерн не выбрать (#547).
 *
 * Поэтому строка двухэтажная: превью во всю ширину панели, имя под ним.
 * Панель 240px, за вычетом полей строки остаётся ~216 -- миниатюра рисуется
 * почти один к одному со своим полем 240x120 (`DEFAULT_BOX`), то есть клетки
 * остаются 18px высотой, а подписи 9px. Это тот размер, где признаки видно.
 * Меньше делать нельзя: подписи становятся полустёртыми, а полустёртый текст
 * хуже отсутствующего -- поэтому масштаб выбран так, чтобы они читались, а не
 * так, чтобы их пришлось гасить.
 *
 * Сколько места дать превью. Второй разобранный вариант -- крупное превью
 * только у того паттерна, на который навели или который выбран. Отвергнут по
 * трём причинам. Первая: просьба была «взять и отсмотреть, что и как
 * сделано», а отсматривают сравнивая -- значит несколько схем должны быть
 * видны разом, а не по одной под указателем. Вторая: строка, растущая под
 * курсором, сдвигает соседние, и в прокручиваемом списке курсор оказывается
 * уже над другой строкой -- та растёт, первая схлопывается, список мигает.
 * Третья: наведения нет ни на касании, ни у того, кто ходит по списку с
 * клавиатуры, и признаки схемы были бы им недоступны вовсе. Цена решения
 * честная: двадцать паттернов занимают около пяти экранов вместо одного.
 * Список от этого остаётся списком -- он прокручивается, а не превращается в
 * набор карточек с портами.
 *
 * Что делать с длинным именем. Имена библиотечных паттернов длинные (31--79
 * знаков), в ширину панели целиком не влезают никак. Имя переносится и не
 * обрезается совсем. Вариант «короткая часть крупно, полная в подсказке»
 * отвергнут: подсказки не видно, пока на неё не навели, на касании её нет, а
 * обрезанным теряется как раз различающий кусок -- «Кратковременная
 * депрессия» и «Кратковременная фасилитация» по ширине панели дают одну и ту
 * же строку «Кратковременная ...». Перенос стоит две-три строки текста -- это
 * дешевле превью над ним и дешевле, чем наводить на каждую из двадцати строк.
 * Подсказки на имени поэтому нет: показывать во всплывающем окне ровно то,
 * что и так написано рядом, -- лишний шум.
 *
 * Вставляет по-прежнему кнопка «+», и превью её щелчок не перехватывает: само
 * превью -- картинка без обработчиков.
 */

import { Thumbnail } from '../catalog/Thumbnail'
import type { Pattern } from '../../model/types'

export interface LibraryRowProps {
  pattern: Pattern
  onInsert: (id: string) => void
}

export function LibraryRow({ pattern, onInsert }: LibraryRowProps) {
  return (
    <div className="sb-row sb-lib">
      <span className="sb-preview">
        {/* Подпись для чтения не глазами говорит про состав, а не повторяет
            имя: имя написано тут же строкой ниже и будет прочитано дважды. */}
        <Thumbnail
          scheme={pattern.scheme}
          label={`схема: ${pattern.counts.neurons} кл., ${pattern.counts.contacts} св.`}
        />
      </span>
      <span className="sb-lib-line">
        <span className="sb-row-text">
          <span className="sb-row-name sb-lib-name">{pattern.name}</span>
          <span className="mono sb-level">
            {pattern.level} · {pattern.counts.neurons} кл.
          </span>
        </span>
        <button
          type="button"
          className="sb-plus"
          title="Вставить в схему"
          onClick={() => onInsert(pattern.id)}
        >
          +
        </button>
      </span>
    </div>
  )
}
