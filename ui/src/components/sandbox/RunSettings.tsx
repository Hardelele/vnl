/**
 * Числа прогона: сколько считать, с каким шагом и с каким зерном (#569).
 *
 * Стоят над дорожками «Активности сети», а не в правой панели, где стояли
 * раньше. Владелец сказал об этом прямо: «настройки прогона почему-то в месте,
 * где у нас расположена детальная информация по конкретным нейронам». Правая
 * панель -- про выбранный объект; длительность и зерно не принадлежат ни
 * клетке, ни связи, и выбор с блока ради них снимать не за что.
 *
 * Именно здесь, а не где-нибудь ещё: это настройки того самого прогона,
 * которым управляют кнопки в шапке этой же панели, и нарисован он ровно под
 * ними -- дорожками. «Сколько считать» стоит рядом с «пустить и отмотать»,
 * потому что это один вопрос, заданный с двух сторон.
 *
 * Строкой, а не столбцом полей: панель делит высоту с холстом, и три поля,
 * выписанные в столбик, отняли бы у дорожек полсотни пикселей ради того, что
 * трогают раз в несколько прогонов.
 */

import type { RunSpec } from '../../model/types'
import { sandboxController } from '../../state/sandbox'
import { NumberField } from './Properties'

export function RunSettings({ run }: { run: RunSpec }) {
  const control = sandboxController
  return (
    <>
      <span
        className="sb-run-label"
        title="Новые числа берёт следующий запуск: уже идущее время досчитывается по прежним"
      >
        Прогон
      </span>
      <NumberField
        label="Длительность, мс"
        step={50}
        value={run.duration}
        onChange={(duration) => void control.setRun({ duration })}
      />
      <NumberField
        label="Шаг, мс"
        step={0.05}
        value={run.dt}
        onChange={(dt) => void control.setRun({ dt })}
      />
      <NumberField
        label="Зерно"
        step={1}
        value={run.seed}
        onChange={(seed) => void control.setRun({ seed })}
      />
      {/* Подпись про «следующий запуск» висит подсказкой на слове «Прогон», а
          не стоит строкой: строка в прибитой панели -- это строка, отнятая у
          дорожек, а сказать надо ровно один раз и ровно тому, кто эти числа
          правит. */}
    </>
  )
}
